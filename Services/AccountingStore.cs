    private static void InitializeAccounting(DbConnection c)
    {
        var identity=c is Npgsql.NpgsqlConnection?"BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY":"INTEGER PRIMARY KEY";
        using var schema=Cmd(c,$"""
            CREATE TABLE IF NOT EXISTS Expenses (
              Id {identity},ExpenseDate TEXT NOT NULL,Category TEXT NOT NULL,Description TEXT NOT NULL,Payee TEXT NOT NULL,
              AmountSatang BIGINT NOT NULL CHECK(AmountSatang>0),Method TEXT NOT NULL CHECK(Method IN ('Cash','Transfer')),Reference TEXT NOT NULL,
              Status TEXT NOT NULL DEFAULT 'Active' CHECK(Status IN ('Active','Void')),
              CreatedBy BIGINT NOT NULL REFERENCES Users(Id),CreatedAt TEXT NOT NULL,
              VoidReason TEXT NOT NULL DEFAULT '',VoidedBy BIGINT REFERENCES Users(Id),VoidedAt TEXT);
            CREATE TABLE IF NOT EXISTS BookingRefunds (
              Id {identity},BookingId BIGINT NOT NULL UNIQUE REFERENCES Bookings(Id),AmountSatang BIGINT NOT NULL CHECK(AmountSatang>0),
              Reason TEXT NOT NULL,Status TEXT NOT NULL DEFAULT 'Pending' CHECK(Status IN ('Pending','Approved','Rejected')),
              RequestedAt TEXT NOT NULL,DecidedAt TEXT,DecidedBy BIGINT REFERENCES Users(Id),AdminNote TEXT NOT NULL DEFAULT '',
              WalletEntryId BIGINT UNIQUE REFERENCES WalletEntries(Id),
              CHECK((Status='Approved' AND WalletEntryId IS NOT NULL) OR (Status<>'Approved' AND WalletEntryId IS NULL)));
            """);schema.ExecuteNonQuery();
    }

    public static void CheckAccountingRange(DateOnly from,DateOnly to)
    {
        if(from>to||to.DayNumber-from.DayNumber>=366)throw new BookingRuleException("เลือกช่วงวันที่ไม่เกิน 366 วัน และวันสิ้นสุดไม่น้อยกว่าวันเริ่มต้น");
    }

    public AccountingPage Accounting(DateOnly from,DateOnly to,long? userId=null)
    {
        CheckAccountingRange(from,to);
        using var c=Open();var entries=new List<AccountingEntry>();
        using(var cmd=Cmd(c,"""
            SELECT p.Id,p.SnapshotJson,CASE WHEN p.MembershipId IS NOT NULL OR EXISTS(
              SELECT 1 FROM WalletEntries w WHERE w.BookingId=p.BookingId AND w.AmountSatang<0) THEN 1 ELSE 0 END
            FROM PaymentReceipts p WHERE ($user IS NULL OR p.UserId=$user)
            """,null,("$user",userId)))
        using(var r=cmd.ExecuteReader())while(r.Read())
        {
            var data=JsonSerializer.Deserialize<ReceiptSnapshot>(r.GetString(1))!;
            entries.Add(new(data.SourceReference,data.PaidAt,data.Kind,data.Kind=="Booking"?data.CourtName:data.PlanName,data.MemberName,data.NetSatang,"Paid",r.GetInt32(2)==1?"Wallet":"External",r.GetString(0)));
        }
        using(var cmd=Cmd(c,"SELECT Id,SnapshotJson FROM DamageReceipts WHERE ($user IS NULL OR UserId=$user)",null,("$user",userId)))
        using(var r=cmd.ExecuteReader())while(r.Read())
        {
            var data=JsonSerializer.Deserialize<ReceiptSnapshot>(r.GetString(1))!;
            entries.Add(new(data.SourceReference,data.PaidAt,"Damage","ค่าซ่อม "+data.CourtName,data.MemberName,data.NetSatang,"Paid","Wallet",r.GetString(0)));
        }
        using(var cmd=Cmd(c,"""
            SELECT t.Id,t.ReviewedAt,u.Name,t.AmountSatang FROM TopUps t JOIN Users u ON u.Id=t.UserId
            WHERE t.Status='Approved' AND t.ReviewedAt IS NOT NULL AND ($user IS NULL OR t.UserId=$user)
            """,null,("$user",userId)))
        using(var r=cmd.ExecuteReader())while(r.Read())entries.Add(new($"TU{r.GetInt64(0):000000}",r.GetString(1),"TopUp","เติมเงินเข้ากระเป๋า",r.GetString(2),r.GetInt64(3),"Paid","External"));
        using(var cmd=Cmd(c,"""
            SELECT d.Id,d.CompletedAt,u.Name,d.AmountSatang FROM DemoPayments d JOIN Users u ON u.Id=d.UserId
            WHERE d.Status='Paid' AND d.CompletedAt IS NOT NULL AND ($user IS NULL OR d.UserId=$user)
            """,null,("$user",userId)))
        using(var r=cmd.ExecuteReader())while(r.Read())entries.Add(new(r.GetString(0),r.GetString(1),"Demo","เครดิตทดลอง (ไม่มีการรับเงินจริง)",r.GetString(2),r.GetInt64(3),"Paid","Demo"));
        foreach(var refund in Refunds(userId).Where(r=>r.Status=="Approved"))entries.Add(new(refund.Reference,refund.DecidedAt!,"Refund",$"คืนค่าจอง CB{refund.BookingId:000000}",refund.MemberName,refund.AmountSatang,"Approved","Wallet"));
        if(!userId.HasValue)foreach(var expense in Expenses(from,to))entries.Add(new($"EX{expense.Id:000000}",expense.Date.ToString("yyyy-MM-dd",System.Globalization.CultureInfo.InvariantCulture)+"T12:00:00+07:00","Expense",expense.Description+" · "+expense.Payee,expense.CreatedBy,expense.AmountSatang,expense.Status,expense.Method));
        using var balance=Cmd(c,"SELECT COALESCE(SUM(AmountSatang),0) FROM WalletEntries WHERE ($user IS NULL OR UserId=$user)",null,("$user",userId));
        return new(from,to,entries.Where(e=>e.Date>=from&&e.Date<=to).OrderByDescending(e=>DateTimeOffset.Parse(e.OccurredAt)).ThenBy(e=>e.Reference).ToList(),(long)balance.ExecuteScalar()!);
    }

    public IReadOnlyList<Expense> Expenses(DateOnly from,DateOnly to)
    {
        CheckAccountingRange(from,to);using var c=Open();using var cmd=Cmd(c,"""
            SELECT e.Id,e.ExpenseDate,e.Category,e.Description,e.Payee,e.AmountSatang,e.Method,e.Reference,e.Status,u.Name,e.CreatedAt,e.VoidReason,e.VoidedAt,COALESCE(v.Name,'')
            FROM Expenses e JOIN Users u ON u.Id=e.CreatedBy LEFT JOIN Users v ON v.Id=e.VoidedBy
            WHERE e.ExpenseDate>=$from AND e.ExpenseDate<=$to ORDER BY e.ExpenseDate DESC,e.Id DESC
            """,null,("$from",CourtTime.Iso(from)),("$to",CourtTime.Iso(to)));using var r=cmd.ExecuteReader();var rows=new List<Expense>();
        while(r.Read())rows.Add(new(r.GetInt64(0),Date(r.GetString(1)),r.GetString(2),r.GetString(3),r.GetString(4),r.GetInt64(5),r.GetString(6),r.GetString(7),r.GetString(8),r.GetString(9),r.GetString(10),r.GetString(11),r.IsDBNull(12)?null:r.GetString(12),r.GetString(13)));
        return rows;
    }

    private static void RequireAdmin(DbConnection c,long adminId,DbTransaction? tx=null)
    {
        using var cmd=Cmd(c,"SELECT COUNT(*) FROM Users WHERE Id=$id AND Role='Admin' AND IsLocked=0",tx,("$id",adminId));
        if((long)cmd.ExecuteScalar()!!=1)throw new BookingRuleException("รายการนี้สำหรับผู้ดูแลระบบเท่านั้น");
    }

    public void AddExpense(long adminId,ExpenseForm form)
    {
        if(!ExpenseForm.Categories.Contains(form.Category)||form.Method is not ("Cash" or "Transfer")||form.Date>CourtTime.Today
            ||string.IsNullOrWhiteSpace(form.Description)||form.Description.Trim().Length is <5 or >500
            ||string.IsNullOrWhiteSpace(form.Payee)||form.Payee.Length>150||string.IsNullOrWhiteSpace(form.Reference)||form.Reference.Length>200
            ||form.Amount<.01m||form.Amount>1000000||decimal.Round(form.Amount,2)!=form.Amount)
            throw new BookingRuleException("ตรวจวันที่จ่าย หมวด รายละเอียด ผู้รับเงิน เลขอ้างอิง และยอดเงินทศนิยมไม่เกิน 2 ตำแหน่ง");
        using var c=Open();RequireAdmin(c,adminId);using var cmd=Cmd(c,"""
            INSERT INTO Expenses(ExpenseDate,Category,Description,Payee,AmountSatang,Method,Reference,CreatedBy,CreatedAt)
            VALUES($date,$category,$description,$payee,$amount,$method,$reference,$admin,$now)
            """,null,("$date",CourtTime.Iso(form.Date)),("$category",form.Category),("$description",form.Description.Trim()),("$payee",form.Payee.Trim()),
            ("$amount",Satang(form.Amount)),("$method",form.Method),("$reference",form.Reference.Trim()),("$admin",adminId),("$now",DateTime.UtcNow.ToString("O")));
        cmd.ExecuteNonQuery();
    }

    public bool VoidExpense(long id,long adminId,string reason)
    {
        if(string.IsNullOrWhiteSpace(reason)||reason.Trim().Length is <5 or >500)throw new BookingRuleException("ระบุเหตุผลยกเลิก 5–500 ตัวอักษร");
        using var c=Open();RequireAdmin(c,adminId);using var cmd=Cmd(c,"UPDATE Expenses SET Status='Void',VoidReason=$reason,VoidedAt=$now,VoidedBy=$admin WHERE Id=$id AND Status='Active'",null,
            ("$id",id),("$reason",reason.Trim()),("$admin",adminId),("$now",DateTime.UtcNow.ToString("O")));
        return cmd.ExecuteNonQuery()==1;
    }

    public IReadOnlyList<BookingRefund> Refunds(long? userId=null,string? status=null)
    {
        using var c=Open();using var cmd=Cmd(c,"""
            SELECT r.Id,r.BookingId,b.UserId,u.Name,u.Email,b.CourtName,r.AmountSatang,r.Reason,r.Status,r.RequestedAt,r.DecidedAt,r.AdminNote,COALESCE(a.Name,'')
            FROM BookingRefunds r JOIN Bookings b ON b.Id=r.BookingId JOIN Users u ON u.Id=b.UserId LEFT JOIN Users a ON a.Id=r.DecidedBy
            WHERE ($user IS NULL OR b.UserId=$user) AND ($status='' OR r.Status=$status) ORDER BY r.Id DESC
            """,null,("$user",userId),("$status",status??""));using var r=cmd.ExecuteReader();var rows=new List<BookingRefund>();
        while(r.Read())rows.Add(new(r.GetInt64(0),r.GetInt64(1),r.GetInt64(2),r.GetString(3),r.GetString(4),r.GetString(5),r.GetInt64(6),r.GetString(7),r.GetString(8),r.GetString(9),r.IsDBNull(10)?null:r.GetString(10),r.GetString(11),r.GetString(12)));
        return rows;
    }

    public void RequestRefund(long userId,RefundForm form)
    {
        if(string.IsNullOrWhiteSpace(form.Reason)||form.Reason.Trim().Length is <5 or >500)throw new BookingRuleException("ระบุเหตุผลขอคืนเงิน 5–500 ตัวอักษร");
        using var c=Open();using var tx=BeginWrite(c);RequireMember(c,userId,tx);
        using var find=Cmd(c,"SELECT NetSatang,Status,PaidAt,PlayDate,StartHour FROM Bookings WHERE Id=$id AND UserId=$user",tx,("$id",form.BookingId),("$user",userId));using var r=find.ExecuteReader();
        if(!r.Read())throw new BookingRuleException("ไม่พบรายการจองของคุณ");
        if(r.IsDBNull(2)||r.GetString(1) is not ("Pending" or "Confirmed")||r.GetInt64(0)<=0||Date(r.GetString(3)).ToDateTime(new TimeOnly(r.GetInt32(4),0))<=CourtTime.Now)
            throw new BookingRuleException("ขอคืนเงินได้เฉพาะรายการที่ชำระแล้ว ยังไม่ยกเลิก และยังไม่ถึงเวลาเริ่มเล่น");
        var amount=r.GetInt64(0);r.Close();
        EnsureNotCheckedIn(c,tx,form.BookingId);
        // ponytail: one full refund request per booking; add partial/refile workflows only when required.
        using var insert=Cmd(c,"INSERT INTO BookingRefunds(BookingId,AmountSatang,Reason,RequestedAt) VALUES($booking,$amount,$reason,$now)",tx,
            ("$booking",form.BookingId),("$amount",amount),("$reason",form.Reason.Trim()),("$now",DateTime.UtcNow.ToString("O")));
        try{insert.ExecuteNonQuery();tx.Commit();}
        catch(DbException ex) when(IsUniqueViolation(ex)){throw new BookingRuleException("รายการนี้มีคำขอคืนเงินแล้ว กรุณาตรวจผลคำขอเดิม");}
    }

    public bool ReviewRefund(long id,long adminId,bool approve,string? note)
    {
        if(note?.Length>1000||(!approve&&string.IsNullOrWhiteSpace(note)))throw new BookingRuleException("ระบุหมายเหตุไม่เกิน 1,000 ตัวอักษร และเหตุผลเมื่อไม่อนุมัติ");
        using var c=Open();using var tx=BeginWrite(c);RequireAdmin(c,adminId,tx);
        using var find=Cmd(c,"""
            SELECT r.BookingId,r.AmountSatang,b.UserId,b.Status,b.PaidAt,b.NetSatang FROM BookingRefunds r JOIN Bookings b ON b.Id=r.BookingId
            WHERE r.Id=$id AND r.Status='Pending'
            """,tx,("$id",id));using var r=find.ExecuteReader();if(!r.Read())return false;
        var bookingId=r.GetInt64(0);var amount=r.GetInt64(1);var user=r.GetInt64(2);
        if(approve&&(r.IsDBNull(4)||r.GetString(3) is not ("Pending" or "Confirmed")||amount!=r.GetInt64(5)))throw new BookingRuleException("สถานะหรือยอดรายการจองเปลี่ยนแล้ว กรุณาตรวจสอบก่อนคืนเงิน");
        r.Close();var now=DateTime.UtcNow.ToString("O");long? entryId=null;
        if(approve)
        {
            EnsureEquipmentReturned(c,tx,bookingId);
            EnsureNotCheckedIn(c,tx,bookingId);
            using var credit=Cmd(c,"INSERT INTO WalletEntries(UserId,AmountSatang,Description,CreatedAt) VALUES($user,$amount,$description,$now) RETURNING Id",tx,
                ("$user",user),("$amount",amount),("$description",$"คืนค่าจอง RF{id:000000} (CB{bookingId:000000})"),("$now",now));entryId=(long)credit.ExecuteScalar()!;
            using var cancel=Cmd(c,"UPDATE Bookings SET Status='Cancelled',CancelledAt=$now WHERE Id=$id",tx,("$id",bookingId),("$now",now));cancel.ExecuteNonQuery();
            using var release=Cmd(c,"DELETE FROM BookedSlots WHERE BookingId=$id",tx,("$id",bookingId));release.ExecuteNonQuery();
        }
        using var update=Cmd(c,"UPDATE BookingRefunds SET Status=$status,DecidedAt=$now,DecidedBy=$admin,AdminNote=$note,WalletEntryId=$entry WHERE Id=$id AND Status='Pending'",tx,
            ("$status",approve?"Approved":"Rejected"),("$now",now),("$admin",adminId),("$note",note?.Trim()??""),("$entry",entryId),("$id",id));
        if(update.ExecuteNonQuery()!=1)throw new BookingRuleException("คำขอนี้ถูกดำเนินการแล้ว กรุณาตรวจสอบสถานะล่าสุด");tx.Commit();return true;
    }
