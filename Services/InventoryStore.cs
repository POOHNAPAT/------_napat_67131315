    private static void EnsureEquipmentReturned(DbConnection c,DbTransaction tx,long bookingId)
    {
        using var cmd=Cmd(c,"SELECT COUNT(*) FROM EquipmentLoans WHERE BookingId=$booking AND IssuedQuantity>GoodQuantity+DamagedQuantity",tx,("$booking",bookingId));
        if((long)cmd.ExecuteScalar()!>0)throw new BookingRuleException("รายการนี้มีอุปกรณ์ที่ยังไม่คืน กรุณารับคืนก่อนยกเลิกหรือคืนเงิน");
    }
