using System.Data.Common;
using CourtBook.Models;

namespace CourtBook.Services;

public partial class BookingStore
{
    private static void InitializeMembershipQuotas(DbConnection c)
    {
        using var tx=BeginWrite(c);
        foreach(var table in new[]{"MembershipPlans","Memberships"})
        foreach(var column in new[]{("MonthlyHours","INTEGER NOT NULL DEFAULT 0"),("QuotaSportTypeId","BIGINT NOT NULL DEFAULT 0"),("QuotaSportName","TEXT NOT NULL DEFAULT ''")})
        {
            if(c is Microsoft.Data.Sqlite.SqliteConnection){
                using var info=Cmd(c,$"PRAGMA table_info({table})",tx);using var r=info.ExecuteReader();var exists=false;
                while(r.Read())exists|=r.GetString(1)==column.Item1;
                r.Close();if(exists)continue;
            }
            using var alter=Cmd(c,$"ALTER TABLE {table} ADD COLUMN {(c is Npgsql.NpgsqlConnection?"IF NOT EXISTS ":"")}{column.Item1} {column.Item2}",tx);alter.ExecuteNonQuery();
        }
        var identity=c is Npgsql.NpgsqlConnection?"BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY":"INTEGER PRIMARY KEY";
        using var schema=Cmd(c,$"""
            CREATE TABLE IF NOT EXISTS MembershipQuotaUses(
              Id {identity},MembershipId BIGINT NOT NULL REFERENCES Memberships(Id),
              BookingId BIGINT NOT NULL UNIQUE REFERENCES Bookings(Id),PeriodStart TEXT NOT NULL,
              Hours INTEGER NOT NULL CHECK(Hours>0));
            CREATE INDEX IF NOT EXISTS IX_MembershipQuotaUses_Period ON MembershipQuotaUses(MembershipId,PeriodStart);
            """,tx);schema.ExecuteNonQuery();tx.Commit();
    }

    private static IReadOnlyList<QuotaBalance> QuotaBalances(DbConnection c,Membership member,DbTransaction? tx)
    {
        if(member.MonthlyHours==0)return [];
        using var cmd=Cmd(c,"""
            SELECT q.PeriodStart,CAST(SUM(q.Hours) AS BIGINT) FROM MembershipQuotaUses q
            JOIN Bookings b ON b.Id=q.BookingId WHERE q.MembershipId=$id AND b.Status<>'Cancelled'
            GROUP BY q.PeriodStart
            """,tx,("$id",member.Id));using var r=cmd.ExecuteReader();var used=new Dictionary<string,int>();
        while(r.Read())used[r.GetString(0)]=checked((int)r.GetInt64(1));
        var periods=new List<QuotaBalance>();
        for(var month=0;member.Starts.AddMonths(month)<member.Ends;month++){
            var start=member.Starts.AddMonths(month);var end=member.Starts.AddMonths(month+1);
            periods.Add(new(start,end<member.Ends?end:member.Ends,member.MonthlyHours,used.GetValueOrDefault(CourtTime.Iso(start))));
        }
        return periods;
    }
}
