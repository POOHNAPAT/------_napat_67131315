    private static void InitializeInventory(DbConnection c)
    {
        var identity=c is Npgsql.NpgsqlConnection?"BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY":"INTEGER PRIMARY KEY";
        var blob=c is Npgsql.NpgsqlConnection?"BYTEA":"BLOB";
        using var tx=BeginWrite(c);
        using var schema=Cmd(c,$"""
            CREATE TABLE IF NOT EXISTS EquipmentStock (
              EquipmentId TEXT PRIMARY KEY REFERENCES RentalEquipment(Id),TotalQuantity INTEGER NOT NULL DEFAULT 0 CHECK(TotalQuantity BETWEEN 0 AND 1000000),
              RepairQuantity INTEGER NOT NULL DEFAULT 0 CHECK(RepairQuantity BETWEEN 0 AND TotalQuantity),Revision INTEGER NOT NULL DEFAULT 0);
            CREATE TABLE IF NOT EXISTS EquipmentLoans (
              BookingId BIGINT NOT NULL REFERENCES Bookings(Id),EquipmentId TEXT NOT NULL REFERENCES RentalEquipment(Id),
              EquipmentName TEXT NOT NULL,Unit TEXT NOT NULL,ReservedQuantity INTEGER NOT NULL CHECK(ReservedQuantity BETWEEN 1 AND 10),
              IssuedQuantity INTEGER NOT NULL DEFAULT 0,GoodQuantity INTEGER NOT NULL DEFAULT 0,DamagedQuantity INTEGER NOT NULL DEFAULT 0,Revision INTEGER NOT NULL DEFAULT 0,
              PRIMARY KEY(BookingId,EquipmentId),CHECK(IssuedQuantity BETWEEN 0 AND ReservedQuantity),
              CHECK(GoodQuantity>=0 AND DamagedQuantity>=0 AND GoodQuantity+DamagedQuantity<=IssuedQuantity));
            CREATE INDEX IF NOT EXISTS IX_EquipmentLoans_Equipment ON EquipmentLoans(EquipmentId);
            CREATE TABLE IF NOT EXISTS EquipmentMovements (
              Id {identity},BookingId BIGINT REFERENCES Bookings(Id),EquipmentId TEXT NOT NULL REFERENCES RentalEquipment(Id),EquipmentName TEXT NOT NULL,
              Kind TEXT NOT NULL CHECK(Kind IN ('Opening','Adjust','Issue','Return')),Quantity INTEGER NOT NULL DEFAULT 0,GoodQuantity INTEGER NOT NULL DEFAULT 0,
              DamagedQuantity INTEGER NOT NULL DEFAULT 0,TotalDelta INTEGER NOT NULL DEFAULT 0,RepairDelta INTEGER NOT NULL DEFAULT 0,
              Note TEXT NOT NULL,ActorId BIGINT NOT NULL REFERENCES Users(Id),CreatedAt TEXT NOT NULL,ImageData {blob},ContentType TEXT,DamageReportId BIGINT REFERENCES DamageReports(Id));
            CREATE INDEX IF NOT EXISTS IX_EquipmentMovements_Equipment ON EquipmentMovements(EquipmentId);
            CREATE INDEX IF NOT EXISTS IX_EquipmentMovements_Booking ON EquipmentMovements(BookingId);
            INSERT INTO EquipmentStock(EquipmentId) SELECT Id FROM RentalEquipment WHERE 1=1 ON CONFLICT DO NOTHING;
            """,tx);schema.ExecuteNonQuery();
        // Preserve old booking quantities; no physical handover is inferred from a reservation.
        using var bookings=Cmd(c,"SELECT Id,EquipmentJson FROM Bookings WHERE EquipmentJson<>'[]'",tx);using var r=bookings.ExecuteReader();
        var old=new List<(long Id,List<BookingEquipment> Items)>();
        while(r.Read())old.Add((r.GetInt64(0),JsonSerializer.Deserialize<List<BookingEquipment>>(r.GetString(1))??[]));r.Close();
        foreach(var booking in old)ReserveEquipment(c,tx,booking.Id,booking.Items);
        if(c is Npgsql.NpgsqlConnection)
        {
            using var rls=Cmd(c,"ALTER TABLE EquipmentStock ENABLE ROW LEVEL SECURITY; ALTER TABLE EquipmentLoans ENABLE ROW LEVEL SECURITY; ALTER TABLE EquipmentMovements ENABLE ROW LEVEL SECURITY",tx);rls.ExecuteNonQuery();
        }
        tx.Commit();
    }

    private static void ReserveEquipment(DbConnection c,DbTransaction tx,long bookingId,IReadOnlyList<BookingEquipment> items)
    {
        foreach(var item in items)
        {
            using var cmd=Cmd(c,"""
                INSERT INTO EquipmentLoans(BookingId,EquipmentId,EquipmentName,Unit,ReservedQuantity)
                SELECT $booking,$equipment,$name,$unit,$quantity WHERE EXISTS(SELECT 1 FROM RentalEquipment WHERE Id=$equipment)
                ON CONFLICT(BookingId,EquipmentId) DO NOTHING
                """,tx,("$booking",bookingId),("$equipment",item.Id),("$name",item.Name),("$unit",item.Unit),("$quantity",item.Quantity));cmd.ExecuteNonQuery();
        }
    }

    private static IReadOnlyList<EquipmentLoan> LoadEquipmentLoans(DbConnection c,DbTransaction? tx=null,long? bookingId=null,string equipmentId="",long? userId=null)
    {
        using var cmd=Cmd(c,"""
            SELECT l.BookingId,l.EquipmentId,l.EquipmentName,l.Unit,l.ReservedQuantity,l.IssuedQuantity,l.GoodQuantity,l.DamagedQuantity,l.Revision,
              b.PlayDate,b.StartHour,b.Hours,CASE WHEN EXISTS(SELECT 1 FROM BookingCheckOuts co WHERE co.BookingId=b.Id) THEN 'CheckedOut' ELSE b.Status END,u.Name,b.PaidAt
            FROM EquipmentLoans l JOIN Bookings b ON b.Id=l.BookingId JOIN Users u ON u.Id=b.UserId
            WHERE ($booking IS NULL OR l.BookingId=$booking) AND ($equipment='' OR l.EquipmentId=$equipment) AND ($user IS NULL OR b.UserId=$user)
            ORDER BY b.PlayDate,b.StartHour,l.BookingId,l.EquipmentId
            """,tx,("$booking",bookingId),("$equipment",equipmentId),("$user",userId));using var r=cmd.ExecuteReader();var rows=new List<EquipmentLoan>();
        while(r.Read())rows.Add(new(r.GetInt64(0),r.GetString(1),r.GetString(2),r.GetString(3),r.GetInt32(4),r.GetInt32(5),r.GetInt32(6),r.GetInt32(7),r.GetInt32(8),Date(r.GetString(9)),r.GetInt32(10),r.GetInt32(11),r.GetString(12),r.GetString(13),r.IsDBNull(14)?null:r.GetString(14)));
        return rows;
    }

    private static int PeakEquipmentDemand(IEnumerable<EquipmentLoan> source,DateTime from,DateTime to)
    {
        var loans=source.ToList();var now=CourtTime.Now;
        // Late returns occupy stock until recorded as returned, including future bookings.
        var baseline=loans.Where(l=>l.Ends<=now||l.BookingStatus=="Cancelled").Sum(l=>l.Outstanding);
        var changes=new List<(DateTime At,int Change)>();
        foreach(var loan in loans.Where(l=>l.BookingStatus is not ("Cancelled" or "CheckedOut")&&l.Ends>now&&l.RemainingReservation>0))
        {
            var start=loan.Starts>from?loan.Starts:from;var end=loan.Ends<to?loan.Ends:to;
            if(start>=end)continue;
            changes.Add((start,loan.RemainingReservation));changes.Add((end,-loan.RemainingReservation));
        }
        var current=baseline;var peak=current;
        foreach(var group in changes.GroupBy(x=>x.At).OrderBy(g=>g.Key))
        {current+=group.Sum(x=>x.Change);peak=Math.Max(peak,current);}
        return peak;
    }

    private static void CheckEquipmentAvailability(DbConnection c,IReadOnlyList<BookingEquipment> chosen,DateOnly date,int[] hours,DbTransaction? tx)
    {
        if(chosen.Count==0)return;
        var start=date.ToDateTime(new TimeOnly(hours.Min(),0));var end=start.AddHours(hours.Length);
        var equipment=GetEquipment(c,null,true,tx).ToDictionary(e=>e.Id);var loans=LoadEquipmentLoans(c,tx);
        foreach(var item in chosen)
        {
            var stock=equipment[item.Id];var available=Math.Max(0,stock.StockQuantity-stock.RepairQuantity-PeakEquipmentDemand(loans.Where(l=>l.EquipmentId==item.Id),start,end));
            if(item.Quantity>available)throw new BookingRuleException($"{item.Name} เหลือ {available} {item.Unit} ในช่วงเวลาที่เลือก กรุณาลดจำนวนหรือเลือกเวลาใหม่");
        }
    }

    public IReadOnlyList<EquipmentAvailability> EquipmentAvailability(long courtId,DateOnly date,int[] hours)
    {
        if(date<CourtTime.Today||hours.Length==0||hours.Distinct().Count()!=hours.Length||hours.Any(h=>!CourtTime.Hours.Contains(h))||hours.Max()-hours.Min()+1!=hours.Length)
            throw new BookingRuleException("เลือกวันและชั่วโมงต่อเนื่องเพื่อดูจำนวนอุปกรณ์พร้อมใช้");
        using var c=Open();var court=GetCourt(c,courtId)??throw new BookingRuleException("ไม่พบสนาม");
        var loans=LoadEquipmentLoans(c);var start=date.ToDateTime(new TimeOnly(hours.Min(),0));var end=start.AddHours(hours.Length);
        return GetEquipment(c,court.SportTypeId).Select(e=>new EquipmentAvailability(e.Id,Math.Max(0,e.StockQuantity-e.RepairQuantity-PeakEquipmentDemand(loans.Where(l=>l.EquipmentId==e.Id),start,end)))).ToList();
    }

    private static IReadOnlyList<EquipmentInventory> InventoryItems(DbConnection c)
    {
        var loans=LoadEquipmentLoans(c);var revisions=new Dictionary<string,int>();
        using(var cmd=Cmd(c,"SELECT EquipmentId,Revision FROM EquipmentStock"))using(var r=cmd.ExecuteReader())while(r.Read())revisions[r.GetString(0)]=r.GetInt32(1);
        return GetEquipment(c,null,true).Select(e=>
        {
            var rows=loans.Where(l=>l.EquipmentId==e.Id).ToList();
            return new EquipmentInventory(e,e.StockQuantity,e.RepairQuantity,revisions.GetValueOrDefault(e.Id),rows.Sum(l=>l.Outstanding),rows.Where(l=>l.Overdue).Sum(l=>l.Outstanding),PeakEquipmentDemand(rows,CourtTime.Now,DateTime.MaxValue));
        }).ToList();
    }

