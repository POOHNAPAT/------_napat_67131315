            CREATE TABLE IF NOT EXISTS Users (
              Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, Name TEXT NOT NULL, Email TEXT NOT NULL UNIQUE,
              PasswordHash TEXT NOT NULL, Role TEXT NOT NULL CHECK(Role IN ('Member','Admin')));
            CREATE TABLE IF NOT EXISTS Courts (
              Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, Name TEXT NOT NULL, Description TEXT NOT NULL,
              PriceSatang BIGINT NOT NULL CHECK(PriceSatang > 0), IsActive INTEGER NOT NULL);
            CREATE TABLE IF NOT EXISTS Promotions (
              Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, Name TEXT NOT NULL, Rule TEXT NOT NULL, Kind TEXT NOT NULL,
              Value100 INTEGER NOT NULL, MinHours INTEGER NOT NULL, MinDays INTEGER NOT NULL,
              MinSpendSatang BIGINT NOT NULL, Starts TEXT NOT NULL, Ends TEXT NOT NULL, IsActive INTEGER NOT NULL);
            CREATE TABLE IF NOT EXISTS Bookings (
              Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, UserId BIGINT NOT NULL REFERENCES Users(Id), CourtId BIGINT NOT NULL REFERENCES Courts(Id),
              CourtName TEXT NOT NULL, PlayDate TEXT NOT NULL, StartHour INTEGER NOT NULL, Hours INTEGER NOT NULL,
              PriceSatang BIGINT NOT NULL, GrossSatang BIGINT NOT NULL, DiscountSatang BIGINT NOT NULL, NetSatang BIGINT NOT NULL,
              PromotionId BIGINT REFERENCES Promotions(Id), PromotionName TEXT NOT NULL, CreatedAt TEXT NOT NULL,
              Status TEXT NOT NULL DEFAULT 'Confirmed');
            CREATE TABLE IF NOT EXISTS BookedSlots (
              CourtId BIGINT NOT NULL REFERENCES Courts(Id), PlayDate TEXT NOT NULL, Hour INTEGER NOT NULL,
              BookingId BIGINT NOT NULL REFERENCES Bookings(Id), PRIMARY KEY(CourtId, PlayDate, Hour));
            CREATE TABLE IF NOT EXISTS BlockedSlots (
              CourtId BIGINT NOT NULL REFERENCES Courts(Id), PlayDate TEXT NOT NULL, Hour INTEGER NOT NULL,
              PRIMARY KEY(CourtId, PlayDate, Hour));
            CREATE INDEX IF NOT EXISTS IX_Bookings_User ON Bookings(UserId);
            CREATE TABLE IF NOT EXISTS SportTypes (Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, Name TEXT NOT NULL UNIQUE);
            
