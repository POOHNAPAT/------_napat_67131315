    public bool SaveEquipmentStock(string id,long adminId,EquipmentStockForm form)
    {
        if(form.TotalQuantity is <0 or >1000000||form.RepairQuantity<0||form.RepairQuantity>form.TotalQuantity||form.Revision<0
            ||string.IsNullOrWhiteSpace(form.Note)||form.Note.Trim().Length is <5 or >1000)
            throw new BookingRuleException("ระบุจำนวนทั้งหมดและจำนวนรอซ่อมให้ถูกต้อง พร้อมเหตุผล 5–1,000 ตัวอักษร");
        using var c=Open();using var tx=BeginWrite(c);RequireAdmin(c,adminId,tx);
        var item=GetEquipment(c,null,true,tx).SingleOrDefault(e=>e.Id==id);if(item is null)return false;
        using var ensure=Cmd(c,"INSERT INTO EquipmentStock(EquipmentId) VALUES($equipment) ON CONFLICT DO NOTHING",tx,("$equipment",id));ensure.ExecuteNonQuery();
        var demand=PeakEquipmentDemand(LoadEquipmentLoans(c,tx,equipmentId:id),CourtTime.Now,DateTime.MaxValue);
        var newCapacity=form.TotalQuantity-form.RepairQuantity;var oldCapacity=item.StockQuantity-item.RepairQuantity;
        if(newCapacity<demand&&newCapacity<oldCapacity)throw new BookingRuleException($"มีการจองหรืออุปกรณ์ค้างคืนสูงสุด {demand} {item.Unit} ไม่สามารถลดจำนวนพร้อมใช้ลงได้ กรุณาจัดการรายการที่เกี่ยวข้องก่อน");
        using var update=Cmd(c,"UPDATE EquipmentStock SET TotalQuantity=$total,RepairQuantity=$repair,Revision=Revision+1 WHERE EquipmentId=$equipment AND Revision=$revision",tx,
            ("$equipment",id),("$total",form.TotalQuantity),("$repair",form.RepairQuantity),("$revision",form.Revision));
        if(update.ExecuteNonQuery()!=1)throw new BookingRuleException("สต็อกเปลี่ยนแล้ว กรุณาโหลดหน้าใหม่ก่อนบันทึก");
        InventoryMovement(c,tx,id,item.Name,"Adjust",adminId,form.Note.Trim(),totalDelta:form.TotalQuantity-item.StockQuantity,repairDelta:form.RepairQuantity-item.RepairQuantity);
        tx.Commit();return true;
    }

    public bool RecordEquipmentHandover(long bookingId,long adminId,EquipmentHandoverForm form,bool returning)
    {
        if(form.Revision<0||string.IsNullOrWhiteSpace(form.Note)||form.Note.Trim().Length is <5 or >1000
            ||form.Quantity is <0 or >10||form.GoodQuantity is <0 or >10||form.DamagedQuantity is <0 or >10
            ||(!returning&&form.Quantity<1)||(returning&&form.GoodQuantity+form.DamagedQuantity<1))
            throw new BookingRuleException("ระบุจำนวนเต็มที่ต้องการส่งมอบหรือรับคืน พร้อมบันทึกสภาพ 5–1,000 ตัวอักษร");
        var image=ReadUploadedImage(form.Image);
        using var c=Open();using var tx=BeginWrite(c);RequireAdmin(c,adminId,tx);
        var loan=LoadEquipmentLoans(c,tx,bookingId,form.EquipmentId).SingleOrDefault();if(loan is null)return false;
        if(loan.Revision!=form.Revision)throw new BookingRuleException("รายการรับ–คืนเปลี่ยนแล้ว กรุณาโหลดหน้าใหม่ ป้องกันบันทึกซ้ำ");
        var stock=GetEquipment(c,null,true,tx).Single(e=>e.Id==form.EquipmentId);long? reportId=null;
        if(!returning)
        {
            if(!loan.CanIssue)throw new BookingRuleException("ส่งมอบได้ในช่วงเวลาเล่นของรายการที่ยืนยันการจองและชำระแล้วเท่านั้น");
            var outstanding=LoadEquipmentLoans(c,tx,equipmentId:form.EquipmentId).Sum(l=>l.Outstanding);
            if(form.Quantity>loan.Unissued||form.Quantity>stock.StockQuantity-stock.RepairQuantity-outstanding)
                throw new BookingRuleException("จำนวนเกินที่จองไว้หรืออุปกรณ์ในคลังไม่เพียงพอ กรุณาตรวจจำนวนค้างคืนและรอซ่อม");
            using var issue=Cmd(c,"UPDATE EquipmentLoans SET IssuedQuantity=IssuedQuantity+$quantity,Revision=Revision+1 WHERE BookingId=$booking AND EquipmentId=$equipment AND Revision=$revision",tx,
                ("$quantity",form.Quantity),("$booking",bookingId),("$equipment",form.EquipmentId),("$revision",form.Revision));issue.ExecuteNonQuery();
        }
        else
        {
            if(form.GoodQuantity+form.DamagedQuantity>loan.Outstanding)throw new BookingRuleException("จำนวนรับคืนรวมเกินจำนวนที่ลูกค้ายังถืออยู่");
            using var receive=Cmd(c,"UPDATE EquipmentLoans SET GoodQuantity=GoodQuantity+$good,DamagedQuantity=DamagedQuantity+$damaged,Revision=Revision+1 WHERE BookingId=$booking AND EquipmentId=$equipment AND Revision=$revision",tx,
                ("$good",form.GoodQuantity),("$damaged",form.DamagedQuantity),("$booking",bookingId),("$equipment",form.EquipmentId),("$revision",form.Revision));receive.ExecuteNonQuery();
            if(form.DamagedQuantity>0)
            {
                using var repair=Cmd(c,"UPDATE EquipmentStock SET RepairQuantity=RepairQuantity+$damaged,Revision=Revision+1 WHERE EquipmentId=$equipment",tx,("$equipment",form.EquipmentId),("$damaged",form.DamagedQuantity));repair.ExecuteNonQuery();
                using var report=Cmd(c,"""
                    INSERT INTO DamageReports(UserId,BookingId,Subject,Category,EquipmentId,EquipmentName,Description,CreatedAt)
                    SELECT UserId,Id,CourtName,'Equipment',$equipment,$name,$description,$now FROM Bookings WHERE Id=$booking RETURNING Id
                    """,tx,("$equipment",form.EquipmentId),("$name",loan.Name),("$description",$"รับคืนชำรุด {form.DamagedQuantity} {loan.Unit}: {form.Note.Trim()}"),("$now",DateTime.UtcNow.ToString("O")),("$booking",bookingId));reportId=(long)report.ExecuteScalar()!;
                if(image is not null)InsertDamageEvidence(c,tx,reportId.Value,adminId,image,"After","สภาพอุปกรณ์ขณะรับคืน");
                RecordDamageEvent(c,tx,reportId.Value,0,"Reported",0,"ผู้ดูแลพบอุปกรณ์ชำรุดขณะรับคืน ยังไม่เรียกเก็บเงิน",adminId);
            }
        }
        InventoryMovement(c,tx,form.EquipmentId,loan.Name,returning?"Return":"Issue",adminId,form.Note.Trim(),bookingId,
            returning?form.GoodQuantity+form.DamagedQuantity:form.Quantity,returning?form.GoodQuantity:0,returning?form.DamagedQuantity:0,repairDelta:returning?form.DamagedQuantity:0,image:image,reportId:reportId);
        tx.Commit();return true;
    }

    private static IReadOnlyList<EquipmentMovement> InventoryMovements(DbConnection c,string equipmentId="",long? bookingId=null,long? userId=null)
    {
        using var cmd=Cmd(c,"""
            SELECT m.Id,m.BookingId,m.EquipmentId,m.EquipmentName,m.Kind,m.Quantity,m.GoodQuantity,m.DamagedQuantity,m.TotalDelta,m.RepairDelta,m.Note,u.Name,m.CreatedAt,
              CASE WHEN m.ImageData IS NULL THEN 0 ELSE 1 END,m.DamageReportId
            FROM EquipmentMovements m JOIN Users u ON u.Id=m.ActorId
            WHERE ($equipment='' OR m.EquipmentId=$equipment) AND ($booking IS NULL OR m.BookingId=$booking)
              AND ($user IS NULL OR EXISTS(SELECT 1 FROM Bookings b WHERE b.Id=m.BookingId AND b.UserId=$user))
            ORDER BY m.Id DESC LIMIT 200
            """,null,("$equipment",equipmentId),("$booking",bookingId),("$user",userId));using var r=cmd.ExecuteReader();var rows=new List<EquipmentMovement>();
        while(r.Read())rows.Add(new(r.GetInt64(0),r.IsDBNull(1)?null:r.GetInt64(1),r.GetString(2),r.GetString(3),r.GetString(4),r.GetInt32(5),r.GetInt32(6),r.GetInt32(7),r.GetInt32(8),r.GetInt32(9),r.GetString(10),r.GetString(11),r.GetString(12),r.GetInt32(13)==1,r.IsDBNull(14)?null:r.GetInt64(14)));
        return rows;
    }

    public CourtImage? EquipmentMovementImage(long id,long? userId=null)
