    private static void InitializeDamageClaims(DbConnection c)
    {
        var identity=c is Npgsql.NpgsqlConnection?"BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY":"INTEGER PRIMARY KEY";
        var blob=c is Npgsql.NpgsqlConnection?"BYTEA":"BLOB";
        using var tx=BeginWrite(c);
        using var cmd=Cmd(c,$"""
            CREATE TABLE IF NOT EXISTS DamageEvidence (
              Id {identity},ReportId BIGINT NOT NULL REFERENCES DamageReports(Id),Kind TEXT NOT NULL CHECK(Kind IN ('Before','After','Invoice','Other')),
              Caption TEXT NOT NULL,ImageData {blob} NOT NULL,ContentType TEXT NOT NULL,UploadedBy BIGINT NOT NULL REFERENCES Users(Id),CreatedAt TEXT NOT NULL);
            CREATE INDEX IF NOT EXISTS IX_DamageEvidence_Report ON DamageEvidence(ReportId);
            CREATE TABLE IF NOT EXISTS DamageClaims (
              ReportId BIGINT PRIMARY KEY REFERENCES DamageReports(Id),Revision INTEGER NOT NULL CHECK(Revision>0),
              Status TEXT NOT NULL CHECK(Status IN ('AwaitingCustomer','Disputed','AwaitingPayment','Paid','Waived')),
              AmountSatang BIGINT NOT NULL CHECK(AmountSatang BETWEEN 0 AND 100000000),Reason TEXT NOT NULL,
              CustomerNote TEXT NOT NULL DEFAULT '',PaidAt TEXT,WalletEntryId BIGINT UNIQUE REFERENCES WalletEntries(Id),
              CHECK((Status='Paid' AND PaidAt IS NOT NULL AND WalletEntryId IS NOT NULL) OR (Status<>'Paid' AND PaidAt IS NULL AND WalletEntryId IS NULL)),
              CHECK((Status='Waived' AND AmountSatang=0) OR (Status<>'Waived' AND AmountSatang>0)));
            CREATE TABLE IF NOT EXISTS DamageClaimEvents (
              Id {identity},ReportId BIGINT NOT NULL REFERENCES DamageReports(Id),Revision INTEGER NOT NULL,Status TEXT NOT NULL,
              AmountSatang BIGINT NOT NULL,Note TEXT NOT NULL,ActorId BIGINT NOT NULL REFERENCES Users(Id),CreatedAt TEXT NOT NULL);
            CREATE INDEX IF NOT EXISTS IX_DamageClaimEvents_Report ON DamageClaimEvents(ReportId);
            CREATE TABLE IF NOT EXISTS DamageReceipts (
              Id TEXT PRIMARY KEY,ReportId BIGINT NOT NULL UNIQUE REFERENCES DamageClaims(ReportId),UserId BIGINT NOT NULL REFERENCES Users(Id),
              SnapshotJson TEXT NOT NULL,CreatedAt TEXT NOT NULL);
            """,tx);
        cmd.ExecuteNonQuery();
        if(c is Npgsql.NpgsqlConnection)
        {
            using var rls=Cmd(c,"ALTER TABLE DamageEvidence ENABLE ROW LEVEL SECURITY; ALTER TABLE DamageClaims ENABLE ROW LEVEL SECURITY; ALTER TABLE DamageClaimEvents ENABLE ROW LEVEL SECURITY; ALTER TABLE DamageReceipts ENABLE ROW LEVEL SECURITY",tx);
            rls.ExecuteNonQuery();
        }
        tx.Commit();
    }

    private static void RecordDamageEvent(DbConnection c,DbTransaction tx,long id,int revision,string status,long amount,string note,long actor)
    {
        using var cmd=Cmd(c,"""
            INSERT INTO DamageClaimEvents(ReportId,Revision,Status,AmountSatang,Note,ActorId,CreatedAt)
            VALUES($id,$revision,$status,$amount,$note,$actor,$now)
            """,tx,("$id",id),("$revision",revision),("$status",status),("$amount",amount),("$note",note),("$actor",actor),("$now",DateTime.UtcNow.ToString("O")));
        cmd.ExecuteNonQuery();
    }

    private static void InsertDamageEvidence(DbConnection c,DbTransaction tx,long id,long actor,CourtImage image,string kind,string caption)
    {
        using var cmd=Cmd(c,"""
            INSERT INTO DamageEvidence(ReportId,Kind,Caption,ImageData,ContentType,UploadedBy,CreatedAt)
            VALUES($id,$kind,$caption,$image,$mime,$actor,$now)
            """,tx,("$id",id),("$kind",kind),("$caption",caption),("$image",image.Data),("$mime",image.ContentType),("$actor",actor),("$now",DateTime.UtcNow.ToString("O")));
        cmd.ExecuteNonQuery();
    }

    public bool AddDamageEvidence(long id,long actor,bool admin,DamageEvidenceForm form)
    {
        if(form.Kind is not ("Before" or "After" or "Invoice" or "Other")||form.Caption?.Length>300)
            throw new BookingRuleException("เลือกประเภทหลักฐานและระบุคำอธิบายไม่เกิน 300 ตัวอักษร");
        var image=ReadUploadedImage(form.Image)??throw new BookingRuleException("กรุณาแนบรูปหลักฐาน");
        using var c=Open();using var tx=BeginWrite(c);
        if(admin)RequireAdmin(c,actor,tx);else RequireMember(c,actor,tx);
        using var find=Cmd(c,"SELECT COUNT(*) FROM DamageReports WHERE Id=$id AND ($admin=1 OR UserId=$actor)",tx,("$id",id),("$admin",admin),("$actor",actor));
        if((long)find.ExecuteScalar()! !=1)return false;
        using var closed=Cmd(c,"SELECT COUNT(*) FROM DamageClaims WHERE ReportId=$id AND Status IN ('Paid','Waived')",tx,("$id",id));
        if((long)closed.ExecuteScalar()!>0)throw new BookingRuleException("เรื่องนี้ปิดแล้ว ไม่สามารถเพิ่มหลักฐานได้");
        using var count=Cmd(c,"SELECT COUNT(*) FROM DamageEvidence WHERE ReportId=$id",tx,("$id",id));
        if((long)count.ExecuteScalar()!>=12)throw new BookingRuleException("แนบหลักฐานได้ไม่เกิน 12 รูปต่อเรื่อง");
        InsertDamageEvidence(c,tx,id,actor,image,form.Kind,form.Caption?.Trim()??"");tx.Commit();return true;
    }

    public CourtImage? DamageEvidenceImage(long id,long actor,bool admin)
    {
        using var c=Open();if(admin)RequireAdmin(c,actor);
        using var cmd=Cmd(c,"""
            SELECT e.ImageData,e.ContentType FROM DamageEvidence e JOIN DamageReports d ON d.Id=e.ReportId
            WHERE e.Id=$id AND ($admin=1 OR d.UserId=$actor)
            """,null,("$id",id),("$actor",actor),("$admin",admin));using var r=cmd.ExecuteReader();
        return r.Read()?new((byte[])r[0],r.GetString(1)):null;
    }

    public bool AssessDamage(long id,long adminId,DamageAssessmentForm form)
    {
        if(string.IsNullOrWhiteSpace(form.Reason)||form.Reason.Trim().Length is <5 or >2000||form.Revision<0
            ||form.Amount<0||form.Amount>1000000||decimal.Round(form.Amount,2)!=form.Amount||(!form.Waive&&form.Amount<=0))
            throw new BookingRuleException("ระบุผลตรวจสอบและรายการค่าซ่อม 5–2,000 ตัวอักษร พร้อมยอดไม่เกิน 1,000,000 บาท ทศนิยมไม่เกิน 2 ตำแหน่ง");
        using var c=Open();using var tx=BeginWrite(c);RequireAdmin(c,adminId,tx);
        using var find=Cmd(c,"SELECT Category,BookingId FROM DamageReports WHERE Id=$id",tx,("$id",id));using var r=find.ExecuteReader();
        if(!r.Read())return false;
        if(!form.Waive&&(r.GetString(0)=="Other"||r.IsDBNull(1)))throw new BookingRuleException("เรียกเก็บได้เฉพาะความเสียหายของสนามหรืออุปกรณ์ที่ผูกกับรายการจอง");
        r.Close();
        if(!form.Waive)
        {
            using var evidence=Cmd(c,"SELECT COUNT(*) FROM DamageEvidence WHERE ReportId=$id",tx,("$id",id));
            if((long)evidence.ExecuteScalar()!<1)throw new BookingRuleException("แนบหลักฐานความเสียหายหรือใบเสนอราคาก่อนแจ้งค่าซ่อม");
        }
        var amount=form.Waive?0:Satang(form.Amount);var status=form.Waive?"Waived":"AwaitingCustomer";var reason=form.Reason.Trim();
        using var previous=Cmd(c,"SELECT Revision,Status FROM DamageClaims WHERE ReportId=$id",tx,("$id",id));using var p=previous.ExecuteReader();
        var exists=p.Read();
        if(exists&&(p.GetInt32(0)!=form.Revision||p.GetString(1) is "Paid" or "Waived")||!exists&&form.Revision!=0)
            throw new BookingRuleException("ข้อมูลเปลี่ยนแล้วหรือเรื่องนี้ปิดแล้ว กรุณาโหลดหน้ารายงานใหม่");
        p.Close();var revision=form.Revision+1;
        using var save=Cmd(c,exists?
            "UPDATE DamageClaims SET Revision=$revision,Status=$status,AmountSatang=$amount,Reason=$reason,CustomerNote='' WHERE ReportId=$id":
            "INSERT INTO DamageClaims(ReportId,Revision,Status,AmountSatang,Reason) VALUES($id,$revision,$status,$amount,$reason)",tx,
            ("$id",id),("$revision",revision),("$status",status),("$amount",amount),("$reason",reason));save.ExecuteNonQuery();
        using var report=Cmd(c,"UPDATE DamageReports SET Status=$status,AdminNote=$note,UpdatedBy=$admin,UpdatedAt=$now WHERE Id=$id",tx,
            ("$id",id),("$status",form.Waive?"Resolved":"InProgress"),("$note",reason),("$admin",adminId),("$now",DateTime.UtcNow.ToString("O")));report.ExecuteNonQuery();
        RecordDamageEvent(c,tx,id,revision,status,amount,reason,adminId);tx.Commit();return true;
    }

    public bool RespondToDamage(long id,long userId,DamageResponseForm form)
    {
        if(form.Decision is not ("Accept" or "Dispute")||form.Note?.Length>2000||form.Revision<1
            ||form.Decision=="Dispute"&&(string.IsNullOrWhiteSpace(form.Note)||form.Note.Trim().Length<5))
            throw new BookingRuleException("เลือกยอมรับหรือขอทบทวน โดยระบุเหตุผลขอทบทวน 5–2,000 ตัวอักษร");
        using var c=Open();using var tx=BeginWrite(c);RequireMember(c,userId,tx);
        var status=form.Decision=="Accept"?"AwaitingPayment":"Disputed";var note=form.Note?.Trim()??"";
        // A customer may dispute an accepted assessment until it has been paid.
        using var cmd=Cmd(c,"""
            UPDATE DamageClaims SET Status=$status,CustomerNote=$note
            WHERE ReportId=$id AND Revision=$revision AND (Status='AwaitingCustomer' OR (Status='AwaitingPayment' AND $decision='Dispute'))
              AND EXISTS(SELECT 1 FROM DamageReports d WHERE d.Id=$id AND d.UserId=$user)
            RETURNING AmountSatang
            """,tx,("$id",id),("$revision",form.Revision),("$status",status),("$note",note),("$decision",form.Decision),("$user",userId));
        var amount=cmd.ExecuteScalar();if(amount is null)return false;
        RecordDamageEvent(c,tx,id,form.Revision,status,(long)amount,note,userId);tx.Commit();return true;
    }

    public bool PayDamage(long id,long userId,int revision)
    {
        using var c=Open();using var tx=BeginWrite(c);RequireMember(c,userId,tx);
        using var find=Cmd(c,"""
            SELECT dc.AmountSatang,dc.Reason,d.Subject,u.Name,u.Email FROM DamageClaims dc
            JOIN DamageReports d ON d.Id=dc.ReportId JOIN Users u ON u.Id=d.UserId
            WHERE dc.ReportId=$id AND dc.Revision=$revision AND dc.Status='AwaitingPayment' AND d.UserId=$user
            """,tx,("$id",id),("$revision",revision),("$user",userId));using var r=find.ExecuteReader();
        if(!r.Read())return false;
        var amount=r.GetInt64(0);var reason=r.GetString(1);var subject=r.GetString(2);var name=r.GetString(3);var email=r.GetString(4);r.Close();
        if(Balance(c,userId,tx)<amount)throw new BookingRuleException("ยอดเงินในกระเป๋าไม่พอ กรุณาเติมเงินก่อนชำระค่าซ่อม");
        var now=DateTime.UtcNow.ToString("O");
        using var debit=Cmd(c,"INSERT INTO WalletEntries(UserId,AmountSatang,Description,CreatedAt) VALUES($user,$amount,$description,$now) RETURNING Id",tx,
            ("$user",userId),("$amount",-amount),("$description",$"ชำระค่าซ่อม DM{id:000000}"),("$now",now));var entry=(long)debit.ExecuteScalar()!;
        using var update=Cmd(c,"UPDATE DamageClaims SET Status='Paid',PaidAt=$now,WalletEntryId=$entry WHERE ReportId=$id AND Status='AwaitingPayment' AND Revision=$revision",tx,
            ("$id",id),("$now",now),("$entry",entry),("$revision",revision));
        if(update.ExecuteNonQuery()!=1)throw new BookingRuleException("สถานะเปลี่ยนแล้ว กรุณาตรวจสอบรายงานล่าสุด");
        var snapshot=new ReceiptSnapshot("Damage",name,email,$"DM{id:000000}",now,"กระเป๋าเงิน COURTBOOK",
            [new("ค่าซ่อม "+subject+" · "+reason,1,"รายการ",amount)],amount,0,amount,"",CourtName:subject);
        using var receipt=Cmd(c,"INSERT INTO DamageReceipts(Id,ReportId,UserId,SnapshotJson,CreatedAt) VALUES($receipt,$id,$user,$snapshot,$now)",tx,
            ("$receipt",$"RC-DM-{id:000000}"),("$id",id),("$user",userId),("$snapshot",JsonSerializer.Serialize(snapshot)),("$now",now));receipt.ExecuteNonQuery();
        using var close=Cmd(c,"UPDATE DamageReports SET Status='Resolved' WHERE Id=$id",tx,("$id",id));close.ExecuteNonQuery();
        RecordDamageEvent(c,tx,id,revision,"Paid",amount,"ชำระจากกระเป๋าเงินและออกใบเสร็จแล้ว",userId);tx.Commit();return true;
    }

    private static IReadOnlyList<DamageReport> LoadDamageClaimDetails(DbConnection c,List<DamageReport> reports)
    {
        if(reports.Count==0)return reports;
        var ids=string.Join(',',reports.Select(r=>r.Id));
        var claims=new Dictionary<long,DamageClaim>();var evidence=new Dictionary<long,List<DamageEvidence>>();var events=new Dictionary<long,List<DamageClaimEvent>>();
        using(var cmd=Cmd(c,$"SELECT ReportId,Revision,Status,AmountSatang,Reason,CustomerNote,PaidAt FROM DamageClaims WHERE ReportId IN ({ids})"))
        using(var r=cmd.ExecuteReader())while(r.Read())claims.Add(r.GetInt64(0),new(r.GetInt64(0),r.GetInt32(1),r.GetString(2),r.GetInt64(3),r.GetString(4),r.GetString(5),r.IsDBNull(6)?null:r.GetString(6)));
        using(var cmd=Cmd(c,$"SELECT e.ReportId,e.Id,e.Kind,e.Caption,u.Name,e.CreatedAt FROM DamageEvidence e JOIN Users u ON u.Id=e.UploadedBy WHERE e.ReportId IN ({ids}) ORDER BY e.Id"))
        using(var r=cmd.ExecuteReader())while(r.Read())
        {
            var id=r.GetInt64(0);if(!evidence.TryGetValue(id,out var list))evidence[id]=list=[];
            list.Add(new(r.GetInt64(1),r.GetString(2),r.GetString(3),r.GetString(4),r.GetString(5)));
        }
        using(var cmd=Cmd(c,$"SELECT e.ReportId,e.Revision,e.Status,e.AmountSatang,e.Note,u.Name,e.CreatedAt FROM DamageClaimEvents e JOIN Users u ON u.Id=e.ActorId WHERE e.ReportId IN ({ids}) ORDER BY e.Id"))
        using(var r=cmd.ExecuteReader())while(r.Read())
        {
            var id=r.GetInt64(0);if(!events.TryGetValue(id,out var list))events[id]=list=[];
            list.Add(new(r.GetInt32(1),r.GetString(2),r.GetInt64(3),r.GetString(4),r.GetString(5),r.GetString(6)));
        }
        return reports.Select(r=>r with {Claim=claims.GetValueOrDefault(r.Id),Evidence=evidence.TryGetValue(r.Id,out var photos)?photos:[],Events=events.TryGetValue(r.Id,out var history)?history:[]}).ToList();
    }
